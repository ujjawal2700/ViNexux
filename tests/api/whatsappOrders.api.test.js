import { adminArrivalService } from '../../backend/src/services/adminArrival.service.js';
import { afterEach, beforeEach, expect, jest, test } from '@jest/globals';
import express from '../../backend/node_modules/express/index.js';
import supertest from 'supertest';
import { Enquiry } from '../../backend/src/models/Enquiry.js';
import { User } from '../../backend/src/models/User.js';
import { Cart } from '../../backend/src/models/Cart.js';
import { Product } from '../../backend/src/models/Product.js';
import { Category } from '../../backend/src/models/Category.js';
import { FooterContent } from '../../backend/src/models/FooterContent.js';
import { createWhatsAppOrder } from '../../backend/src/controllers/enquiry.controller.js';
import { listAllEnquiries } from '../../backend/src/services/enquiry.service.js';
import { whatsappOrderSchema } from '../../backend/src/validators/enquiry.validator.js';
import { validate } from '../../backend/src/middlewares/validate.js';
import { errorHandler } from '../../backend/src/middlewares/errorHandler.js';
const id = '507f1f77bcf86cd799439011', productId = '507f1f77bcf86cd799439012';
const requestId = '310d5563-49b4-4405-a44b-c350c2d07051';
const address = { line1: '123 Main Road', line2: '', city: 'Kota', state: 'Rajasthan', pincode: '324002' };
const payload = { requestId, addressId: id, deliveryAddress: address, selectedProductIds: [productId], contactName: 'Customer', contactEmail: 'customer@example.test', contactPhone: '9876543210', whatsappNumber: '9876543210', message: 'Deliver next week' };
let request, stored, cart, product;
beforeEach(() => {
  jest.spyOn(adminArrivalService, 'publish').mockResolvedValue();
  stored = null;
  cart = { items: [{ productId, quantity: 2 }], save: jest.fn() };
  product = { _id: productId, name: 'Camera', sku: 'CAM-1', modelNumber: 'M-1', model: 'Mini PT', variant: '4G', categoryId: id, isActive: true, stockQuantity: 10, standardPrice: 100, images: [] };
  const user = { fullName: 'Customer', role: 'customer', email: 'customer@example.test', phone: '9876543210', savedAddresses: { id: value => value === id ? address : null } };
  jest.spyOn(User, 'findById').mockImplementation(() => ({ then: resolve => Promise.resolve(user).then(resolve), select: () => ({ lean: async () => user }) }));
  jest.spyOn(Cart, 'findOne').mockResolvedValue(cart);
  jest.spyOn(Product, 'find').mockResolvedValue([product]);
  jest.spyOn(Product, 'findOneAndUpdate').mockResolvedValue(null);
  jest.spyOn(Category, 'find').mockReturnValue({ select: () => ({ lean: async () => [{ _id: id, isActive: true }] }) });
  jest.spyOn(Enquiry, 'findOne').mockImplementation(filter => filter.requestId ? Promise.resolve(stored) : ({ sort() { return this; }, lean: async () => null }));
  jest.spyOn(Enquiry, 'create').mockImplementation(async data => { stored = new Enquiry({ ...data, _id: id }); await stored.validate(); return stored; });
  jest.spyOn(FooterContent, 'findOne').mockReturnValue({ lean: async () => ({ whatsappNumbers: [{ number: '9876543211' }] }) });
  const app = express(); app.use(express.json());
  app.use((req, res, next) => { if (!req.headers['x-user']) return res.sendStatus(401); req.user = { _id: req.headers['x-user'] }; next(); });
  app.post('/whatsapp', validate(whatsappOrderSchema), createWhatsAppOrder); app.use(errorHandler);
  request = supertest(app);
});
afterEach(() => jest.restoreAllMocks());
const submit = body => request.post('/whatsapp').set('x-user', id).send({ ...payload, ...body });
test('saves a server-priced WhatsApp lead before returning the chat URL without clearing cart or deducting stock', async () => {
  const res = await submit();
  expect(res.status).toBe(201);
  expect(stored.source).toBe('whatsapp');
  expect(stored.items[0]).toMatchObject({ productName: 'Camera', quantity: 2, priceShown: 100 });
  expect(stored.deliveryAddress.city).toBe('Kota');
  const url = new URL(res.body.data.whatsappUrl);
  expect(url.searchParams.get('phone')).toBe('919876543211');
  expect(url.searchParams.get('text')).toContain(stored.enquiryNumber);
  expect(url.searchParams.get('text')).toContain('Estimated Total: ₹200');
  expect(cart.save).not.toHaveBeenCalled(); expect(cart.items).toHaveLength(1);
  expect(Product.findOneAndUpdate).not.toHaveBeenCalled();
});
test('retry returns the original lead even if cart changed, without creating duplicate follow-ups', async () => {
  const first = await submit(); cart.items = [];
  const second = await submit();
  expect(second.status).toBe(201);
  expect(second.body.data.enquiry._id).toBe(first.body.data.enquiry._id);
  expect(Enquiry.create).toHaveBeenCalledTimes(1);
  expect(adminArrivalService.publish).toHaveBeenCalledTimes(1);
});
test('does not capture invalid, unauthenticated, unavailable, or unowned-address orders', async () => {
  expect((await request.post('/whatsapp').send(payload)).status).toBe(401);
  expect((await submit({ contactPhone: '' })).status).toBe(400);
  expect((await submit({ priceShown: 1 })).status).toBe(400);
  expect((await submit({ addressId: productId })).status).toBe(400);
  product.stockQuantity = 0;
  expect((await submit()).status).toBe(409);
  expect(Enquiry.create).not.toHaveBeenCalled();
});
test('WhatsApp admin queue only returns WhatsApp leads and regular queue includes legacy records', async () => {
  jest.spyOn(Enquiry, 'countDocuments').mockResolvedValue(0);
  jest.spyOn(Enquiry, 'find').mockReturnValue({ populate() { return this; }, sort() { return this; }, skip() { return this; }, limit() { return this; }, lean: async () => [] });
  await listAllEnquiries({ source: 'whatsapp' });
  expect(Enquiry.countDocuments).toHaveBeenLastCalledWith({ source: 'whatsapp' });
  await listAllEnquiries({ source: 'storefront', userType: 'customer' });
  expect(Enquiry.countDocuments).toHaveBeenLastCalledWith({ source: { $ne: 'whatsapp' }, userType: 'customer' });
});
