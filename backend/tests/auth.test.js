import assert from 'node:assert/strict';
import mongoose from 'mongoose';
import supertest from '../../node_modules/supertest/index.js';
import app from '../src/app.js';
import { config } from '../src/config/env.js';
import { User } from '../src/models/User.js';
import { OtpVerification } from '../src/models/OtpVerification.js';
import { authService } from '../src/services/auth.service.js';
import { accountRequests } from './helpers/accounts.js';
await mongoose.connect(config.mongodbUri);
const request = supertest(app);
const raw = async (path, options = {}, body) => {
  const response = await request[(options.method || 'GET').toLowerCase()](path).set(options.headers || {}).send(body);
  return { status: response.status, body: response.body };
};
const accounts = accountRequests(raw);
const auth = (method, path, token, body) => raw(`/api/auth${path}`, { method, headers: { Authorization: `Bearer ${token}` } }, body);
let checks = 0;
const check = (condition, message) => { assert.ok(condition, message); checks++; };
try {
  const input = { fullName: 'Jane Customer', email: 'auth-customer@example.test', phone: '9876543210', password: 'SecurePassword123!', role: 'customer' };
  const invalid = await raw('/api/auth/signup', { method: 'POST' }, input);
  check(invalid.status === 400, 'Signup requires legal acceptance and phone verification');
  const signed = await accounts('/api/auth/signup', { method: 'POST' }, input);
  check(signed.status === 201, 'Verified phone and legal consent permit signup');
  const session = signed.body.data;
  check(session.user.accountStatus === 'active' && session.accessToken && session.refreshToken, 'Signup immediately issues an active authenticated session');
  const dealer = await accounts('/api/auth/signup', { method: 'POST' }, { ...input, email: 'auth-dealer@example.test', phone: '9876543211', role: 'dealer' });
  check(dealer.status === 201 && dealer.body.data.user.role === 'dealer', 'Dealer signup includes compliance and location fields');
  const nonexistent = await raw('/api/auth/send-otp', { method: 'POST' }, { identifier: 'missing@example.test', purpose: 'login' });
  check(nonexistent.status === 404, 'Unknown account cannot request a login OTP');
  const me = await auth('GET', '/me', session.accessToken);
  check(me.status === 200 && me.body.data.user.email === input.email, 'Authenticated profile belongs to the logged-in customer');
  check(!JSON.stringify(me.body).includes('passwordHash'), 'Profile responses do not reveal password hashes');
  await OtpVerification.deleteMany({ identifier: input.phone });
  await authService.sendOtp({ identifier: input.phone, purpose: 'login', portal: 'customer' });
  const wrong = await raw('/api/auth/verify-otp', { method: 'POST' }, { identifier: input.phone, otp: '999999', purpose: 'login', portal: 'customer' });
  check(wrong.status === 400, 'Wrong OTP is rejected');
  const conflict = await raw('/api/auth/verify-otp', { method: 'POST' }, { identifier: input.phone, otp: '123456', purpose: 'login', portal: 'customer' });
  check(conflict.status === 200 && conflict.body.data.sessionConflict && conflict.body.data.conflictTicket, 'Second customer device requires explicit session takeover');
  const ticket = conflict.body.data.conflictTicket;
  const takeovers = await Promise.all([0, 1].map(() => raw('/api/auth/force-login', { method: 'POST' }, { conflictTicket: ticket })));
  check(takeovers.filter(result => result.status === 200).length === 1 && takeovers.filter(result => result.status === 400).length === 1, 'Concurrent takeover requests consume the conflict ticket exactly once');
  const forced = takeovers.find(result => result.status === 200);
  check(forced.status === 200 && forced.body.data.accessToken, 'Confirmed takeover creates a replacement session');
  const replacement = forced.body.data;
  const reused = await raw('/api/auth/force-login', { method: 'POST' }, { conflictTicket: ticket });
  check(reused.status >= 400, 'A consumed takeover ticket cannot be reused');
  check((await auth('GET', '/me', session.accessToken)).status === 401, 'Takeover revokes the old device');
  check((await auth('GET', '/me', replacement.accessToken)).status === 200, 'Replacement device remains authorized');
  const refreshed = await raw('/api/auth/refresh-token', { method: 'POST' }, { refreshToken: replacement.refreshToken });
  check(refreshed.status === 200 && refreshed.body.data.refreshToken !== replacement.refreshToken, 'Refresh token rotates');
  check((await raw('/api/auth/refresh-token', { method: 'POST' }, { refreshToken: replacement.refreshToken })).status === 401, 'Old refresh token is rejected');
  const current = refreshed.body.data;
  check((await auth('POST', '/logout', current.accessToken, {})).status === 200, 'Logout succeeds');
  check((await auth('GET', '/me', current.accessToken)).status === 401, 'Logged-out access tokens are rejected');
  await User.updateOne({ email: input.email }, { $set: { accountStatus: 'blocked', status: 'blocked' } });
  check((await raw('/api/auth/send-otp', { method: 'POST' }, { identifier: input.phone, purpose: 'login' })).status === 403, 'Blocked account cannot log in');
  const adminSignup = await raw('/api/auth/signup', { method: 'POST' }, { ...input, role: 'admin', acceptPrivacyPolicy: true, acceptTerms: true });
  check(adminSignup.status === 400, 'Signup cannot self-assign admin access');
  console.log(`Authentication integration passed ${checks} checks.`);
} finally { await mongoose.disconnect(); }
