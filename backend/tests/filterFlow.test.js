import assert from 'node:assert/strict';
import { test } from 'node:test';
import mongoose from 'mongoose';
import app from '../src/app.js';
import { config } from '../src/config/env.js';
import { Product } from '../src/models/Product.js';
import { Brand } from '../src/models/Brand.js';
import { Category } from '../src/models/Category.js';

test('hierarchical and multi-value filters keep stable options and accurate disjunctive counts', async () => {
  assert.match(process.env.TEST_DATABASE_NAME || '', /^vinexus_full_test_/);
  await mongoose.connect(config.mongodbUri);
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  try {
    const security = await Category.create({ name: 'CCTV', slug: 'filter-cctv' });
    const networking = await Category.create({ name: 'Networking', slug: 'filter-networking' });
    const ip = await Category.create({ name: 'IP Cameras', slug: 'filter-ip', parentId: security._id, filterDefinitions: [{ key: 'Resolution', label: 'Resolution', inputType: 'multi-select', options: ['2 MP', '4 MP', '8 MP'], isFilterable: true }] });
    const analog = await Category.create({ name: 'Analog Cameras', slug: 'filter-analog', parentId: security._id });
    const switches = await Category.create({ name: 'Switches', slug: 'filter-switches', parentId: networking._id });
    const bullet = await Category.create({ name: 'Bullet', slug: 'filter-bullet', parentId: ip._id });
    const dome = await Category.create({ name: 'Dome', slug: 'filter-dome', parentId: ip._id });
    const poe = await Category.create({ name: 'PoE Switches', slug: 'filter-poe', parentId: switches._id });
    const hidden = await Category.create({ name: 'Hidden', slug: 'filter-hidden', isActive: false });
    const make = (sku, category, brand, resolution, power, fields = {}) => Product.create({ sku, name: `Camera ${sku}`, modelNumber: `MODEL-${sku}`, categoryId: category._id, isActive: true, stockQuantity: 10, standardPrice: 100, specifications: [{ key: 'Brand', value: brand }, { key: 'Resolution', value: resolution }, { key: 'Power', value: power }, ...Array.from({ length: 10 }, (_, index) => ({ key: `Feature ${index}`, value: `Value ${index}` }))], ...fields });
    const a = await make('A', bullet, 'Acme', '4 MP', 'PoE');
    const b = await make('B', dome, 'Acme', '8 MP', 'PoE', { stockQuantity: 0 });
    const c = await make('C', dome, 'Beta', '4 MP', '12V', { isLowStock: true });
    const m = await make('M', bullet, 'Acme', '4 MP', 'PoE', { categoryIds: [security._id, ip._id, bullet._id, dome._id] });
    await make('E', analog, 'Acme', '2 MP', '12V');
    const network = await Product.create({ sku: 'NETWORK', name: 'PoE Network Switch', categoryId: poe._id, stockQuantity: 6, isActive: true, specifications: [{ key: 'Brand', value: 'Beta' }, { key: 'Ports', value: '16' }] });
    await make('HIDDEN', hidden, 'Acme', '4 MP', 'PoE');
    const base = `http://127.0.0.1:${server.address().port}${config.apiBaseUrl}`;
    const get = async (query = {}) => {
      const response = await fetch(`${base}/products?${new URLSearchParams(query)}`); const body = await response.json();
      assert.equal(response.status, 200, JSON.stringify(body)); return body.data;
    };
    const ids = result => result.products.map(product => product._id).sort();
    await Brand.create({ name: 'Acme', slug: 'custom-acme' });
    const brandRoute = await get({ brandSlug: 'custom-acme' });
    assert.equal(brandRoute.resolvedBrand, 'Acme'); assert.equal(brandRoute.pagination.total, 4);
    const all = await get(); assert.equal(all.pagination.total, 6);
    assert.equal(all.facets.categories.find(category => category._id === String(security._id)).count, 5, 'multi-category assignments must not double-count header totals');
    assert.equal(all.facets.categories.find(category => category._id === String(dome._id)).count, 3);
    assert.ok(all.facets.specs.length > 8, 'detailed specifications are no longer arbitrarily truncated');
    assert.equal((await get({ headerCategory: String(security._id) })).pagination.total, 5);
    assert.equal((await get({ headerCategory: `${security._id},${networking._id}` })).pagination.total, 6);
    assert.equal((await get({ headerCategory: String(security._id), mainCategory: String(ip._id), subCategory: `${bullet._id},${dome._id}` })).pagination.total, 4);
    assert.deepEqual(ids(await get({ subCategory: String(dome._id) })), [b, c, m].map(product => String(product._id)).sort());
    const selection = { headerCategory: String(security._id), brand: 'ACME', specs: JSON.stringify({ Resolution: ['4 MP'], Power: ['PoE'] }) };
    const filtered = await get(selection); assert.deepEqual(ids(filtered), [String(a._id), String(m._id)].sort());
    assert.ok(filtered.facets.categories.some(category => category._id === String(networking._id)), 'other headers remain present');
    assert.equal(filtered.facets.brands.find(brand => brand.name === 'BETA').count, 0);
    const resolution = filtered.facets.specs.find(spec => spec.key === 'Resolution');
    assert.equal(resolution.values.find(value => value.val === '8 MP').count, 1, 'same-spec alternatives ignore their own selection');
    assert.equal(filtered.facets.specs.find(spec => spec.key === 'Power').values.find(value => value.val === '12V').count, 0, 'counts respect the other spec and brand');
    const noBrand = await get({ ...selection, brand: 'ACME,BETA' });
    assert.equal(noBrand.facets.specs.find(spec => spec.key === 'Power').values.find(value => value.val === '12V').count, 1);
    const multi = await get({ headerCategory: String(security._id), specs: JSON.stringify({ Resolution: ['4 MP', '8 MP'], Power: ['PoE'] }) });
    assert.deepEqual(ids(multi), [a, b, m].map(product => String(product._id)).sort());
    assert.deepEqual(ids(await get({ specs: JSON.stringify({ Resolution: ['4 MP'], resolution: ['8 MP'], Power: ['PoE'] }) })), ids(multi));
    const zero = await get({ headerCategory: String(networking._id), specs: JSON.stringify({ Resolution: ['4 MP'] }) });
    assert.equal(zero.pagination.total, 0); assert.equal(zero.facets.categories.length, all.facets.categories.length); assert.equal(zero.facets.specs.length, all.facets.specs.length);
    const none = await get({ availability: 'none' }); assert.equal(none.pagination.total, 0); assert.equal(none.facets.brands.length, 2);
    assert.equal((await get({ headerCategory: 'unknown' })).pagination.total, 0);
    assert.equal((await get({ category: 'unknown' })).pagination.total, 0);
    assert.equal((await get({ specs: '{"__proto__":["missing"]}' })).pagination.total, 0);
    assert.deepEqual(ids(await get({ ...selection, includeFacets: 'false' })), ids(filtered));
    const paged = []; for (let page = 1; page <= 2; page++) paged.push(...ids(await get({ ...selection, limit: '1', page: String(page) })));
    assert.deepEqual(paged.sort(), ids(filtered));
    const typo = await get({ search: 'Camrea', headerCategory: String(networking._id) });
    assert.equal(typo.pagination.total, 0); assert.equal(typo.searchMode, 'fuzzy'); assert.ok(typo.facets.categories.length > 0, 'fuzzy zero-result combinations retain their correction context');
    const exactNoResult = await get({ search: 'Camera', headerCategory: String(networking._id) });
    assert.equal(exactNoResult.pagination.total, 0); assert.notEqual(exactNoResult.searchMode, 'fuzzy');
    const searched = await get({ search: 'Camera' }); assert.equal(searched.pagination.total, 5); assert.ok(!ids(searched).includes(String(network._id)));
  } finally { await new Promise(resolve => server.close(resolve)); await mongoose.disconnect(); }
});
