import assert from 'node:assert/strict';
import { mock } from 'node:test';
import { randomUUID } from 'node:crypto';
import bcrypt from 'bcryptjs';
import mongoose from 'mongoose';
import supertest from '../../node_modules/supertest/index.js';
import app from '../src/app.js';
import { User } from '../src/models/User.js';
import { Session } from '../src/models/Session.js';
import { AccessRole } from '../src/models/AccessRole.js';
import { EmployeeWorkCredential } from '../src/models/EmployeeWorkCredential.js';
import { employeeWorkService } from '../src/services/employeeWork.service.js';
import { DEFAULT_WORK_SCHEDULE } from '../../shared/employeeWorkSchedule.js';
import { generateAccessToken } from '../src/utils/token.util.js';
import { config } from '../src/config/env.js';
const dbName = `vinexus_employee_work_test_${Date.now()}`;
let connected = false;
try {
  await mongoose.connect('mongodb://127.0.0.1:27019/?replicaSet=vinexusAccessTest', { dbName }); connected = true;
  await Promise.all(Object.values(mongoose.models).map(model => model.init()));
  mock.timers.enable({ apis: ['Date'], now: new Date('2026-11-30T07:59:00+05:30') });
  const clock = time => mock.timers.setTime(new Date(time).getTime());
  const request = supertest(app), initialPassword = 'InitialOffice123!';
  const owner = await User.create({ fullName: 'Office Owner', email: 'office.owner@example.test', phone: '9999999999', role: 'admin', accountStatus: 'active', status: 'active', passwordHash: await bcrypt.hash(initialPassword, 10) });
  const ownerSession = await Session.create({ userId: owner._id, userType: 'admin', sessionId: randomUUID(), issuedAt: new Date(), createdAt: new Date(), expiresAt: new Date(Date.now() + 7 * 86400000) });
  const token = (user, session) => generateAccessToken({ userId: user._id, role: user.role, sessionId: session.sessionId });
  const api = (method, path, user = owner, session = ownerSession) => request[method](`/api${path}`).auth(token(user, session), { type: 'bearer' });
  const check = (response, status = 200) => { assert.equal(response.status, status, JSON.stringify(response.body)); return response.body.data; };
  const workSchedule = { ...structuredClone(DEFAULT_WORK_SCHEDULE), enabled: true };
  workSchedule.days.saturday.end = '15:00';
  const role = await AccessRole.create({ name: 'Daytime team', workSchedule, permissions: { products: { read: true, write: true } } });
  const staff = [];
  for (let i = 0; i < 2; i++) staff.push(await User.create({ fullName: `Employee ${i}`, email: `office.employee${i}@example.test`, phone: `988888888${i}`, role: 'admin', isEmployee: true, accessRoleId: role._id, accountStatus: 'active', status: 'active', passwordHash: await bcrypt.hash(initialPassword, 10) }));
  const reveal = async employee => check(await api('post', `/admin/access/employees/${employee._id}/daily-password`));
  const send = (employee, password) => request.post('/api/auth/send-otp').send({ identifier: employee.email, portal: 'admin', password });
  const signin = async (employee, password, shareLocation = true) => {
    const otpRequest = send(employee, password);
    if (!shareLocation) otpRequest.set('X-Test-No-Admin-Location', '1');
    check(await otpRequest);
    const verifyRequest = request.post('/api/auth/verify-otp').send({ identifier: employee.email, portal: 'admin', otp: config.mockOtpCode });
    if (!shareLocation) verifyRequest.set('X-Test-No-Admin-Location', '1');
    return check(await verifyRequest);
  };
  assert.equal((await reveal(staff[0])).available, false, 'No password is issued before 8 AM');
  assert.equal(await EmployeeWorkCredential.countDocuments(), 0);
  clock('2026-11-30T08:00:00+05:30'); await employeeWorkService.tick();
  const first = await reveal(staff[0]), other = await reveal(staff[1]);
  assert.equal(first.available, true); assert.notEqual(first.password, other.password);
  assert.notEqual(first.password, initialPassword); assert.equal(first.window.loginFrom, '2026-11-30T03:30:00.000Z');
  await employeeWorkService.tick(); assert.equal((await reveal(staff[0])).password, first.password, 'Repeated worker runs never rotate twice in one day');
  check(await send(staff[0], first.password), 403, 'Cannot sign in before 9 AM');
  clock('2026-11-30T09:00:00+05:30');
  check(await send(staff[0], initialPassword), 401, 'The original manual password cannot bypass scheduled access');
  const signed = await signin(staff[0], first.password);
  const employeeSession = await Session.findOne({ sessionId: signed.session.sessionId });
  assert.equal(employeeSession.expiresAt.toISOString(), '2026-11-30T13:50:00.000Z');
  assert.ok(employeeSession.loginLocation.latitude); assert.equal(signed.user.employeeWorkWindow.warnAt, '2026-11-30T13:15:00.000Z');
  const own = check(await api('get', '/auth/me', staff[0], employeeSession));
  assert.ok(!JSON.stringify(own).includes(first.password));
  check(await api('post', `/admin/access/employees/${staff[0]._id}/daily-password`, staff[0], employeeSession), 403);
  check(await request.post('/api/auth/send-otp').send({ identifier: staff[0].email, purpose: 'password-reset', portal: 'admin' }), 403);
  check(await api('put', '/auth/profile', staff[0], employeeSession).send({ currentPassword: first.password, newPassword: 'PermanentOverride123!' }), 403);
  clock('2026-11-30T12:00:00+05:30');
  check(await api('post', '/auth/logout', staff[0], employeeSession));
  const again = await signin(staff[0], first.password, false);
  assert.equal((await Session.findOne({ sessionId: again.session.sessionId })).loginLocation, undefined);
  const refreshed = check(await request.post('/api/auth/refresh-token').set('X-Test-No-Admin-Location', '1').send({ refreshToken: again.refreshToken }));
  again.refreshToken = refreshed.refreshToken;
  assert.notEqual(again.session.sessionId, employeeSession.sessionId, 'Early sign-out keeps the day password usable');
  const active = await Session.findOne({ sessionId: again.session.sessionId });
  clock('2026-11-30T18:45:00+05:30');
  assert.equal(check(await api('get', '/admin/access/self', staff[0], active)).access.employeeWorkWindow.expiresAt, '2026-11-30T13:50:00.000Z');
  clock('2026-11-30T19:20:00+05:30');
  check(await request.post('/api/auth/refresh-token').send({ refreshToken: again.refreshToken }), 401);
  check(await api('get', '/auth/me', staff[0], active), 401);
  check(await send(staff[0], first.password), 403);
  await employeeWorkService.tick();
  const expiredCredential = await EmployeeWorkCredential.findOne({ userId: staff[0]._id, workDate: '2026-11-30' }).select('+passwordHash +passwordCiphertext');
  assert.ok(expiredCredential.discardedAt); assert.equal(expiredCredential.passwordCiphertext, undefined); assert.equal(expiredCredential.passwordHash, undefined);
  assert.equal((await User.findById(staff[0]._id).select('+passwordHash')).passwordHash, undefined);
  clock('2026-12-01T07:59:00+05:30'); assert.equal((await reveal(staff[0])).available, false);
  clock('2026-12-01T08:00:00+05:30'); await employeeWorkService.tick();
  const next = await reveal(staff[0]); assert.notEqual(next.password, first.password); assert.notEqual(next.password, (await reveal(staff[1])).password);
  clock('2026-12-01T10:00:00+05:30'); check(await send(staff[0], first.password), 401);
  await signin(staff[0], next.password);
  check(await send(staff[0], next.password));
  const employeeDetails = { fullName: staff[0].fullName, email: staff[0].email, phone: staff[0].phone, accessRoleId: String(role._id) };
  check(await api('put', `/admin/access/employees/${staff[0]._id}`).send({ ...employeeDetails, accountStatus: 'blocked' }));
  check(await api('put', `/admin/access/employees/${staff[0]._id}`).send({ ...employeeDetails, accountStatus: 'active' }));
  const restored = await reveal(staff[0]); assert.equal(restored.available, true); assert.notEqual(restored.password, next.password, 'Unblocking issues a fresh credential inside the current window');
  check(await request.post('/api/auth/verify-otp').send({ identifier: staff[0].email, portal: 'admin', otp: config.mockOtpCode }), 401, 'A pending OTP cannot revive the discarded password');
  await signin(staff[0], restored.password);
  clock('2026-12-05T10:00:00+05:30'); await employeeWorkService.tick();
  const saturday = await reveal(staff[0]); assert.equal(saturday.window.expiresAt, '2026-12-05T09:50:00.000Z');
  const satLogin = await signin(staff[0], saturday.password);
  const satSession = await Session.findOne({ sessionId: satLogin.session.sessionId });
  check(await send(staff[0], saturday.password)); // Pending OTP must not survive timetable/password changes.
  const changedSchedule = structuredClone(workSchedule); changedSchedule.days.saturday.end = '17:00';
  check(await api('put', `/admin/access/roles/${role._id}`).send({ name: role.name, description: '', isActive: true, permissions: { products: { read: true, write: true } }, workSchedule: changedSchedule }));
  assert.equal((await Session.findById(satSession._id)).isActive, false);
  const changed = await reveal(staff[0]); assert.notEqual(changed.password, saturday.password); assert.equal(changed.window.expiresAt, '2026-12-05T11:50:00.000Z');
  check(await request.post('/api/auth/verify-otp').send({ identifier: staff[0].email, portal: 'admin', otp: config.mockOtpCode }), 401);
  clock('2026-12-06T10:00:00+05:30'); await employeeWorkService.tick();
  assert.equal((await reveal(staff[0])).window.working, false); check(await send(staff[0], changed.password), 403);
  // Missing, denied, invalid and stale locations do not block admin access.
  for (const location of [null, { status: 'denied' }, { status: 'available', latitude: 91, longitude: 75, accuracy: 10, timestamp: Date.now() }, { status: 'available', latitude: 25, longitude: 75, accuracy: 10, timestamp: Date.now() - 3600000 }]) {
    const req = api('get', '/admin/access/self');
    if (location) req.set('X-Admin-Location', JSON.stringify(location)); else req.set('X-Test-No-Admin-Location', '1');
    check(await req);
  }
  check(await request.post('/api/auth/send-otp').set('X-Test-No-Admin-Location', '1').send({ identifier: owner.email, portal: 'admin', password: initialPassword }));
  const customer = await User.create({ fullName: 'Customer', email: 'location.customer@example.test', phone: '9777777777', role: 'customer', accountStatus: 'active', status: 'active' });
  const customerSession = await Session.create({ userId: customer._id, userType: 'customer', sessionId: randomUUID(), issuedAt: new Date(), createdAt: new Date(), expiresAt: new Date(Date.now() + 3600000) });
  check(await api('get', '/auth/me', customer, customerSession).set('X-Test-No-Admin-Location', '1'));
  console.log('Employee work integration passed: per-day timetables, 8 AM unique encrypted passwords, one-hour early login, cutoff/refresh enforcement, password disposal, early logout reuse, schedule edits, OTP binding and optional admin location.');
} finally {
  mock.timers.reset();
  if (connected) await mongoose.connection.dropDatabase();
  await mongoose.disconnect();
}
